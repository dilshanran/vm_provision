#!/usr/bin/env bash
# Select AWS or Azure remote state without editing backend.tf.
#
# Usage (from an environment directory, e.g. environments/dev):
#   ../../scripts/init-backend.sh aws
#   ../../scripts/init-backend.sh azure
#   CLOUD_PROVIDER=azure ../../scripts/init-backend.sh
#
set -euo pipefail

CLOUD="${1:-${CLOUD_PROVIDER:-azure}}"
CLOUD="$(echo "$CLOUD" | tr '[:upper:]' '[:lower:]')"

OVERRIDE_FILE="backend_override.tf"

case "$CLOUD" in
  aws)
    # AWS path kept for later; ensure backend.tf uses backend "s3" {} when enabling.
    rm -f "$OVERRIDE_FILE"
    BACKEND_CONFIG="backend/aws.hcl"
    ;;
  azure)
    # backend.tf already defaults to azurerm; override is a no-op safety net.
    cat > "$OVERRIDE_FILE" <<'EOF'
# Generated by init-backend.sh — do not commit or edit.
terraform {
  backend "azurerm" {}
}
EOF
    BACKEND_CONFIG="backend/azure.hcl"
    ;;
  *)
    echo "Unknown cloud provider: $CLOUD (expected aws or azure)" >&2
    exit 1
    ;;
esac

echo "Initializing Terraform with $CLOUD backend ($BACKEND_CONFIG)"
terraform init -reconfigure -backend-config="$BACKEND_CONFIG"
